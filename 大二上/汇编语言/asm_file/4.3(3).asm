CODES SEGMENT
    ASSUME CS:CODES,DS:DATAS,SS:STACKS
START:
    MOV AX, 0
    MOV DX, 0
	MOV AX, 0B800H
	MOV ES, AX
    MOV SI, 0 
    MOV CX, 100 

SUM_LOOP:
    MOV AX, ES:[B800H + SI] ; 取一个16位无符号数
    ADD DX, AX ; 加到DX.AX中
    ADC DX, 0 ; 处理进位
    ADD SI, 2 
    DEC CX
    JNZ SUM_LOOP 

    MOV AH, 4CH
    INT 21H

CODES ENDS
    END START
