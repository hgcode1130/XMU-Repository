    MOV AX,DATAS
    MOV DS,AX

    MOV CX, 100 

ARRAY_LOOP:
    DEC BYTE PTR [array + CX - 1]
    DEC CX
    JNZ ARRAY_LOOP 

    MOV AH, 4CH
    INT 21H

CODES ENDS
    END START
